import type { Experience } from '../../data/schema';
import { RowActions, TextArea, TextInput } from '../components/fields';
import { ListEditor } from '../components/ListEditor';
import { StringList } from '../components/StringList';
import { moveItem, removeItem } from '../lib/paths';
import type { SectionProps } from '../lib/sections';

function ExperienceFields({ entry, update }: { entry: Experience; update: (patch: Partial<Experience>) => void }) {
  return (
    <>
      <div className="grid-2">
        <TextInput label="Role" value={entry.role} onChange={(v) => update({ role: v ?? '' })} />
        <TextInput label="Organization" value={entry.org} onChange={(v) => update({ org: v ?? '' })} />
        <TextInput
          label="Period"
          value={entry.period}
          onChange={(v) => update({ period: v ?? '' })}
          placeholder="2024 – 2025"
        />
        <TextInput label="Location" optional value={entry.location} onChange={(v) => update({ location: v })} />
      </div>
      <StringList
        label="Bullets"
        noun="bullet"
        multiline
        items={entry.bullets}
        onChange={(v) => update({ bullets: v })}
      />
    </>
  );
}

const newExperience = (): Experience => ({
  role: '',
  org: '',
  period: '',
  bullets: [],
});

export function ResumeSection({ draft, set }: SectionProps) {
  const resume = draft.resume;
  const highlights = resume.highlights ?? [];
  const setHighlights = (v: string[]) => set(['resume', 'highlights'], v);

  return (
    <>
      <div className="grid-2">
        <TextInput
          label="Formal PDF path"
          mono
          value={resume.file}
          onChange={(v) => set(['resume', 'file'], v ?? '')}
          hint="Site-relative path under public/, regenerated by npm run build:resume."
        />
        <TextInput label="Updated" mono value={resume.updated} onChange={(v) => set(['resume', 'updated'], v ?? '')} />
      </div>
      <TextInput label="Headline" value={resume.headline} onChange={(v) => set(['resume', 'headline'], v ?? '')} />
      <TextArea label="Summary" value={resume.summary} onChange={(v) => set(['resume', 'summary'], v ?? '')} rows={3} />

      <ListEditor<Experience>
        label="Experience"
        noun="position"
        items={resume.experience}
        onChange={(v) => set(['resume', 'experience'], v)}
        title={(e) => (e.role && e.org ? `${e.role} · ${e.org}` : e.role || e.org)}
        create={newExperience}
      >
        {(entry, update) => <ExperienceFields entry={entry} update={update} />}
      </ListEditor>

      <ListEditor<Experience>
        label="Activities"
        noun="activity"
        addLabel="Add activity"
        items={resume.activities}
        onChange={(v) => set(['resume', 'activities'], v)}
        title={(e) => (e.role && e.org ? `${e.role} · ${e.org}` : e.role || e.org)}
        create={newExperience}
      >
        {(entry, update) => <ExperienceFields entry={entry} update={update} />}
      </ListEditor>

      <fieldset className="list">
        <legend className="field__label">Highlighted projects</legend>
        <p className="field__hint">Checked projects are listed on the resume, in the order below.</p>
        <div className="choices">
          {draft.projects.map((p, i) => {
            const checked = highlights.includes(p.id);
            return (
              <label key={`${p.id}-${i}`} className="check check--boxed">
                <input
                  type="checkbox"
                  checked={checked}
                  onChange={(e) =>
                    setHighlights(
                      e.target.checked
                        ? [...highlights.filter((h) => h !== p.id), p.id]
                        : highlights.filter((h) => h !== p.id),
                    )
                  }
                />
                <span className="check__text">
                  {p.title || p.id}
                  <span className="mono muted"> {p.id}</span>
                </span>
              </label>
            );
          })}
        </div>
        {highlights.length ? (
          <ol className="list__rows list__rows--compact">
            {highlights.map((id, i) => {
              const known = draft.projects.some((p) => p.id === id);
              return (
                <li key={`${id}-${i}`} className="list__row list__row--compact">
                  <span className={`mono${known ? '' : ' muted'}`}>
                    {i + 1}. {id}
                    {known ? '' : ' (unknown project id)'}
                  </span>
                  <RowActions
                    index={i}
                    count={highlights.length}
                    label={`highlight ${id}`}
                    onMove={(a, b) => setHighlights(moveItem(highlights, a, b))}
                    onRemove={(idx) => setHighlights(removeItem(highlights, idx))}
                  />
                </li>
              );
            })}
          </ol>
        ) : null}
      </fieldset>
    </>
  );
}
